#!/usr/bin/env python3
"""Derive the closed-set detector taxonomy FROM THE DATA — never hand-authored.

Reads the label vocabulary actually present in the assembled sources (flywheel
labels are first-class: they are what real users photograph and verify;
bootstrap labels are secondary), embeds each distinct label with
nomic-embed-text:v1.5 via local Ollama, clusters on cosine distance, and names
each cluster after its most frequent member.

Only the DETECTOR track needs this: RF-DETR is a closed-set architecture and
must be told how many classes exist. The VLM track is open-vocabulary and uses
no taxonomy at all.

Regenerated by `make train-dataset-detr`, so the class list evolves with the
data instead of being maintained by hand.

Usage:
  python3 training/dataset/derive_taxonomy.py --flywheel datasets/export-… \
      --bootstrap training/data/bootstrap/coco-household [--threshold 0.25]
      [--min-count 1] [--out training/dataset/derived_taxonomy.json]
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from cluster import DEFAULT_THRESHOLD, agglomerative  # noqa: E402
from coco_sources import gather_sources  # noqa: E402
from embed import DEFAULT_MODEL, EmbedderUnavailable, embed_texts  # noqa: E402
from label_norm import normalize_label  # noqa: E402

DEFAULT_OUT = Path(__file__).with_name("derived_taxonomy.json")
CACHE_PATH = Path(__file__).resolve().parents[1] / "data" / "embed_cache.json"


def collect_vocabulary(entries) -> tuple:
    """(Counter of normalized label -> count, set of flywheel-origin labels)."""
    counts: Counter = Counter()
    flywheel_labels: set = set()
    for entry in entries:
        for ann in entry.annotations:
            cat_name = entry.category_names.get(ann.get("category_id"), "")
            if entry.kind == "flywheel":
                raw = ann.get("attributes", {}).get("label") or cat_name
            else:
                raw = cat_name
            label = normalize_label(raw)
            if not label:
                continue
            counts[label] += 1
            if entry.kind == "flywheel":
                flywheel_labels.add(label)
    return counts, flywheel_labels


def build_clusters(counts: Counter, threshold: float, embedder=embed_texts) -> tuple:
    """(clusters, degraded). Each cluster: name, count, members.

    Cluster naming prefers the most frequent member, tie-broken alphabetically
    for determinism. Falls back to one-class-per-label when the embedder is
    unreachable, so a dataset build never hard-fails."""
    labels = sorted(counts)
    if not labels:
        return [], False
    try:
        vectors = embedder(labels)
    except EmbedderUnavailable as e:
        print(
            f"WARNING: embedder unavailable ({e}).\n"
            "WARNING: falling back to EXACT-LABEL classes — no synonym merging.\n"
            "WARNING: start Ollama and rerun for a properly clustered taxonomy.",
            file=sys.stderr,
        )
        return (
            [{"name": lbl, "count": counts[lbl], "members": [lbl]} for lbl in labels],
            True,
        )

    groups = agglomerative([vectors[lbl] for lbl in labels], threshold)
    clusters = []
    for group in groups:
        members = [labels[i] for i in group]
        name = min(members, key=lambda m: (-counts[m], m))
        clusters.append(
            {
                "name": name,
                "count": sum(counts[m] for m in members),
                "members": sorted(members),
            }
        )
    clusters.sort(key=lambda c: (-c["count"], c["name"]))
    return clusters, False


def assign_ids(clusters) -> list:
    return [{"id": i + 1, **c} for i, c in enumerate(clusters)]


def member_to_class(clusters) -> dict:
    """Label -> cluster name. This mapping is DATA the clustering produced, not
    a curated alias file."""
    return {m: c["name"] for c in clusters for m in c["members"]}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--flywheel", type=Path, default=None)
    parser.add_argument("--bootstrap", type=Path, action="append", default=[])
    parser.add_argument("--threshold", type=float, default=DEFAULT_THRESHOLD)
    parser.add_argument("--min-count", type=int, default=1, help="drop labels rarer than this")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--stats", action="store_true", help="print distribution only")
    args = parser.parse_args()

    if not args.flywheel and not args.bootstrap:
        parser.error("need --flywheel and/or --bootstrap")

    entries = gather_sources(args.flywheel, args.bootstrap, [])
    counts, flywheel_labels = collect_vocabulary(entries)
    kept = Counter({k: v for k, v in counts.items() if v >= args.min_count})

    clusters, degraded = build_clusters(
        kept, args.threshold, lambda labels: embed_texts(labels, cache_path=CACHE_PATH)
    )
    clusters = assign_ids(clusters)

    singletons = [c for c in clusters if len(c["members"]) == 1]
    print(f"distinct labels:         {len(counts)}")
    print(f"labels kept (>= {args.min_count}):    {len(kept)}")
    print(f"derived classes:         {len(clusters)}")
    print(f"single-member classes:   {len(singletons)}")
    print(f"flywheel-origin labels:  {len(flywheel_labels)}")
    print(f"embedder:                {'FALLBACK (exact labels)' if degraded else DEFAULT_MODEL}")
    long_tail = [c for c in clusters if c["count"] <= 5]
    print(f"classes with <=5 instances: {len(long_tail)}")
    print("\ntop 25 derived classes:")
    for c in clusters[:25]:
        extra = f"  <- {', '.join(m for m in c['members'] if m != c['name'])}" if len(c["members"]) > 1 else ""
        print(f"  {c['count']:6d}  {c['name']}{extra}")
    # Every merge is printed so a human can spot a bad threshold immediately.
    merges = [c for c in clusters if len(c["members"]) > 1]
    print(f"\nsynonym merges ({len(merges)}):")
    for c in merges:
        print(f"  {c['name']} <- {', '.join(m for m in c['members'] if m != c['name'])}")

    if flywheel_labels:
        uncovered = sorted(flywheel_labels - set(member_to_class(clusters)))
        print(f"\nflywheel labels not represented: {len(uncovered)}")
        if uncovered:
            print("  " + ", ".join(uncovered[:40]))

    if args.stats:
        return 0

    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator": "training/dataset/derive_taxonomy.py",
        "parameters": {
            "embedding_model": "exact-label-fallback" if degraded else DEFAULT_MODEL,
            "linkage": "average",
            "metric": "cosine",
            "threshold": args.threshold,
            "min_count": args.min_count,
            "sources": {
                "flywheel": str(args.flywheel) if args.flywheel else None,
                "bootstrap": [str(b) for b in args.bootstrap],
            },
        },
        "degraded": degraded,
        "classes": clusters,
    }
    args.out.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"\nwrote {len(clusters)} classes -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
